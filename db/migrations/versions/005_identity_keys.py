"""Give the two AUTOINCREMENT keys a Postgres identity.

Revision ID: 005_identity_keys
Revises: 004_lowercase_identifiers

SQLite's ``INTEGER PRIMARY KEY AUTOINCREMENT`` hands out the next id when an
INSERT omits the column.  Postgres has no such implicit behaviour, so the
migrated schema declared ``snapshot_id BIGINT NOT NULL`` with no default and
the TSM snapshot sweep failed on its first insert:

    psycopg2.errors.NotNullViolation: null value in column "snapshot_id"
    of relation "tsm_snapshot" violates not-null constraint

Two tables in the source declare AUTOINCREMENT, and both of them rely on it:
``tsm_snapshot.snapshot_id`` and ``journal.id``.  The rest of the integer
primary keys (``tsm_region_price.key_id``, ``blizzard_items.itemid`` and so on)
are supplied by their callers and are left alone -- adding an identity to a
column whose value means something would be worse than the bug being fixed.

``GENERATED BY DEFAULT`` rather than ``ALWAYS``: a caller that does know the id
must still be able to write it, which is exactly what SQLite allowed.
"""
from __future__ import annotations

from alembic import op

revision = "005_identity_keys"
down_revision = "004_lowercase_identifiers"
branch_labels = None
depends_on = None


#: (table, column) for every AUTOINCREMENT key in the SQLite source.
_KEYS = (
    ("journal", "id"),
    ("tsm_snapshot", "snapshot_id"),
)


def upgrade() -> None:
    for table, column in _KEYS:
        op.execute(
            f'ALTER TABLE "{table}" ALTER COLUMN "{column}"'
            f" ADD GENERATED BY DEFAULT AS IDENTITY"
        )
        # The rows already migrated carry explicit ids, so the sequence has to
        # start past them.  Without this the first generated id would be 1 and
        # collide with an existing row.
        op.execute(
            f"SELECT setval(pg_get_serial_sequence('{table}', '{column}'),"
            f' COALESCE((SELECT MAX("{column}") FROM "{table}"), 0) + 1, false)'
        )


def downgrade() -> None:
    for table, column in _KEYS:
        op.execute(
            f'ALTER TABLE "{table}" ALTER COLUMN "{column}"'
            f" DROP IDENTITY"
        )
