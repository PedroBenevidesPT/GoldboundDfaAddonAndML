"""The new-dataset alert: when it fires, and when it must not.

The pipeline exports the dataset every six hours and announces it through
`run_pipeline.notify_new_dataset`.  An alert per export would be a
heartbeat, and a heartbeat is the thing a player mutes -- so the decision
is "did the content change", and this file pins what "changed" means.

The first version of this check hashed the whole file.  That covers
`generatedAt`, so every export looked new: measured on the real pipeline,
two exports a minute apart differed only in the timestamp and in the fourth
decimal of `psell` (0.1619 -> 0.1618), and the alert fired both times.
"""
from __future__ import annotations

from pathlib import Path

import pytest

import run_pipeline
from woweconomy.pricing.dataset import dataset_content_signature


HEADER = """-- Generated by the DfA pricing engine.  Do not edit by hand.
-- schema 2, engine 1.0, generated 1792746001
-- Regenerate with: python scripts/dfa_pricing_export.py

DFA_ESTIMATE = {
\tversion = 2,
\tgeneratedAt = 1792746001,
\titemCount = 237,
"""

BODY = """\trealms = {
\t\t["Dragonmaw"] = { psell = 0.1619, price = 123400 },
\t},
}
"""


def dataset_text(generated_at: int = 1792746001, psell: str = "0.1619") -> str:
    header = HEADER.replace("1792746001", str(generated_at))
    return header + BODY.replace("0.1619", psell)


def write(tmp_path: Path, text: str) -> Path:
    path = tmp_path / "DFA_Estimate_Data.lua"
    path.write_text(text, encoding="utf-8")
    return path


# ---------------------------------------------------------------------------
# the signature
# ---------------------------------------------------------------------------
def test_the_signature_ignores_when_the_dataset_was_built():
    assert (dataset_content_signature(dataset_text(generated_at=1792746001))
            == dataset_content_signature(dataset_text(generated_at=1792749999)))


def test_the_signature_ignores_drift_in_the_fourth_decimal():
    """Measured on two real exports a minute apart."""
    assert (dataset_content_signature(dataset_text(psell="0.1619"))
            == dataset_content_signature(dataset_text(psell="0.1618")))


def test_the_signature_notices_a_change_worth_reporting():
    assert (dataset_content_signature(dataset_text(psell="0.1619"))
            != dataset_content_signature(dataset_text(psell="0.4019")))


def test_the_signature_notices_a_changed_count():
    changed = dataset_text().replace("itemCount = 237", "itemCount = 240")
    assert dataset_content_signature(dataset_text()) != \
        dataset_content_signature(changed)


# ---------------------------------------------------------------------------
# the pipeline's fingerprint
# ---------------------------------------------------------------------------
def test_the_fingerprint_of_a_missing_file_is_empty(tmp_path: Path):
    assert run_pipeline.dataset_fingerprint(tmp_path / "nothing.lua") == ""


def test_the_fingerprint_follows_the_content_not_the_file(tmp_path: Path):
    """The regression: two exports of one dataset are one alert."""
    first = write(tmp_path, dataset_text(generated_at=1792746001))
    before = run_pipeline.dataset_fingerprint(first)

    # an hour later, same data: new timestamp, same content
    write(tmp_path, dataset_text(generated_at=1792749601))

    assert run_pipeline.dataset_fingerprint(first) == before


def test_the_fingerprint_changes_when_the_data_does(tmp_path: Path):
    path = write(tmp_path, dataset_text(psell="0.1619"))
    before = run_pipeline.dataset_fingerprint(path)

    write(tmp_path, dataset_text(psell="0.4019"))

    assert run_pipeline.dataset_fingerprint(path) != before


def test_the_fingerprint_survives_a_dataset_with_odd_bytes(tmp_path: Path):
    """A half-written or mis-encoded file must not stop the pipeline."""
    path = tmp_path / "DFA_Estimate_Data.lua"
    path.write_bytes(b"DFA_ESTIMATE = { itemCount = 1 }\xff\xfe")

    assert run_pipeline.dataset_fingerprint(path) != ""


# ---------------------------------------------------------------------------
# the alert itself
# ---------------------------------------------------------------------------
def test_the_alert_names_the_counts_and_the_status_breakdown(tmp_path: Path):
    text = dataset_text().replace(
        "\titemCount = 237,\n",
        "\titemCount = 237,\n\tpriceCount = 31184,\n"
        '\tpredictionStatus = {\n\t\t["baseline_only"] = 237,\n\t},\n')
    path = write(tmp_path, text)

    facts = run_pipeline.dataset_facts(path)
    alert = run_pipeline.dataset_alert(facts, run_pipeline.dataset_fingerprint(path))

    body = "\n".join(alert.lines)
    assert "itemCount: 237" in body
    assert "priceCount: 31184" in body
    assert "status: baseline_only: 237" in body
    assert alert.title.startswith("New DfA dataset")


def test_the_alert_has_one_key_so_the_cooldown_can_work(tmp_path: Path):
    """Every dataset shares the key; the fingerprint is what decides."""
    facts = run_pipeline.dataset_facts(write(tmp_path, dataset_text()))
    first = run_pipeline.dataset_alert(facts, "a" * 64)
    second = run_pipeline.dataset_alert(facts, "b" * 64)

    assert first.key == second.key


def test_facts_of_a_missing_dataset_are_empty(tmp_path: Path):
    assert run_pipeline.dataset_facts(tmp_path / "nothing.lua") == {}
